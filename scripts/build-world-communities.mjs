// scripts/build-world-communities.mjs — turns the Meetup harvest notes in
// research/world/batch*.txt into data/communities-world.ts.
//
//   node scripts/build-world-communities.mjs
//
// Each line: city | meetup-group-slug | name | category | next event | "Sun 22 Nov" | mode | what it does
// Every row came from meetup.com/find/?location=<code>&source=EVENTS on
// 16–17 Nov 2026 and had a dated upcoming event on that page. The script
// refuses rows whose weekday doesn't match the 2026 calendar date, unknown
// cities/categories and duplicate groups within a city.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = 'research/world';
const HARVESTED = '2026-11-17';
const YEAR = 2026;

// Meetup "find" location codes (the page each row was read from).
const LOC = {
  'San Francisco': 'us--ca--San%20Francisco', 'New York': 'us--ny--New%20York', 'Los Angeles': 'us--ca--Los%20Angeles',
  Seattle: 'us--wa--Seattle', Austin: 'us--tx--Austin', Boston: 'us--ma--Boston', Chicago: 'us--il--Chicago',
  'Washington DC': 'us--dc--Washington', Miami: 'us--fl--Miami', Denver: 'us--co--Denver', Atlanta: 'us--ga--Atlanta',
  'San Diego': 'us--ca--San%20Diego', Toronto: 'ca--on--Toronto', Vancouver: 'ca--bc--Vancouver',
  'Mexico City': 'mx--Mexico%20City', 'São Paulo': 'br--Sao%20Paulo', 'Buenos Aires': 'ar--Buenos%20Aires',
  London: 'gb--London', Edinburgh: 'gb--Edinburgh', Dublin: 'ie--Dublin', Paris: 'fr--Paris', Berlin: 'de--Berlin',
  Munich: 'de--M%C3%BCnchen', Amsterdam: 'nl--Amsterdam', Barcelona: 'es--Barcelona', Madrid: 'es--Madrid',
  Lisbon: 'pt--Lisbon', Milan: 'it--Milano', Zurich: 'ch--Zurich', Vienna: 'at--Vienna', Prague: 'cz--Prague',
  Warsaw: 'pl--Warsaw', Copenhagen: 'dk--Copenhagen', Stockholm: 'se--Stockholm', Istanbul: 'tr--Istanbul',
  Dubai: 'ae--Dubai', 'Abu Dhabi': 'ae--Abu%20Dhabi', Doha: 'qa--Doha', Riyadh: 'sa--Riyadh', 'Tel Aviv': 'il--Tel%20Aviv-Yafo',
  'Cape Town': 'za--Cape%20Town', Nairobi: 'ke--Nairobi', Lagos: 'ng--Lagos', Singapore: 'sg--Singapore',
  'Hong Kong': 'hk--Hong%20Kong', Tokyo: 'jp--Tokyo', Seoul: 'kr--Seoul', Shanghai: 'cn--Shanghai', Beijing: 'cn--Beijing',
  Taipei: 'tw--Taipei', Bangkok: 'th--Bangkok', 'Kuala Lumpur': 'my--Kuala%20Lumpur', Jakarta: 'id--Jakarta',
  Manila: 'ph--Manila', 'Ho Chi Minh City': 'vn--Ho%20Chi%20Minh%20City', Kathmandu: 'np--Kathmandu',
  Sydney: 'au--Sydney', Melbourne: 'au--Melbourne', Auckland: 'nz--Auckland',
};
const CATS = new Set(['running', 'cycling', 'sports', 'fitness', 'outdoors', 'tech', 'startup', 'creative', 'books', 'food', 'social', 'language', 'cause', 'wellbeing', 'parents', 'pets', 'professional', 'games', 'dating', 'women', 'civic']);
const MON = { Nov: 10, Dec: 11 };
const DAY = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const slugify = (s) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const rows = [];
const errors = [];
const seen = new Set();
for (const f of readdirSync(DIR).filter((f) => /^batch\d+\.txt$/.test(f)).sort()) {
  for (const [i, raw] of readFileSync(`${DIR}/${f}`, 'utf8').split('\n').entries()) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const p = line.split(' | ').map((s) => s.trim());
    if (p.length !== 8) { errors.push(`${f}:${i + 1} expected 8 fields, got ${p.length}`); continue; }
    const [city, path, name, category, event, date, mode, what] = p;
    if (!LOC[city]) errors.push(`${f}:${i + 1} unknown city ${city}`);
    if (!CATS.has(category)) errors.push(`${f}:${i + 1} unknown category ${category}`);
    const m = /^(Sun|Mon|Tue|Wed|Thu|Fri|Sat) (\d{1,2}) (Nov|Dec)$/.exec(date);
    if (!m) { errors.push(`${f}:${i + 1} bad date ${date}`); continue; }
    const d = new Date(Date.UTC(YEAR, MON[m[3]], Number(m[2])));
    if (DAY[d.getUTCDay()] !== m[1]) errors.push(`${f}:${i + 1} ${date} is not a ${m[1]} in ${YEAR}`);
    const key = `${city}|${path}`;
    if (seen.has(key)) { errors.push(`${f}:${i + 1} duplicate ${key}`); continue; }
    seen.add(key);
    rows.push({ city, path, name, category, event, date: `${date} ${YEAR}`, iso: d.toISOString().slice(0, 10), mode: mode.toLowerCase(), what });
  }
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const q = (s) => JSON.stringify(s);
const out = [];
out.push(`// ============================================================
// data/communities-world.ts — GENERATED by scripts/build-world-communities.mjs
// from research/world/batch*.txt. Do not edit by hand; edit the notes and re-run.
//
// ${rows.length} Meetup groups in ${new Set(rows.map((r) => r.city)).size} cities outside India. Each one showed a dated
// upcoming event on meetup.com/find (EVENTS view) when harvested on ${HARVESTED};
// that event is the row's activitySignal. Left out on purpose: self-help /
// "healing" funnels, religious or spiritual groups, astrology, MLM, sales,
// investing / crypto / real-estate, nightlife promoters, university-only
// student chapters, groups whose page showed another city, and online-only
// groups dressed up as local ones. Meetup lists no prices on the find page,
// so pricing stays "Ask organiser".
// ============================================================
import { c, type Community, type CommunityCategory } from './communities';

const D = ${q(HARVESTED)};
const LOC: Record<string, string> = ${JSON.stringify(LOC)};
type Mode = 'in-person' | 'online' | 'hybrid';

const slugPart = (s: string) => s.toLowerCase().normalize('NFKD').replace(/%[0-9a-f]{2}/gi, '').replace(/[\\u0300-\\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function w(city: string, path: string, name: string, category: CommunityCategory, what: string, next: string, mode: Mode): Community {
  const url = \`https://www.meetup.com/\${path}/\`;
  const tagline = what.endsWith('.') ? what : \`\${what}.\`;
  return c({
    slug: \`w-\${slugPart(city)}-\${slugPart(path)}\`.slice(0, 80).replace(/-$/, ''),
    name, city, category, tagline,
    description: \`\${tagline} Runs on Meetup — the next event, venue and any fee are on the group page; RSVP there.\`,
    tags: ['meetup', 'international'],
    meets: { cadence: 'irregular', summary: \`Next: \${next}\` },
    join: { url, platform: 'meetup', cta: 'RSVP on Meetup' },
    links: { meetup: url },
    source: { url: \`https://www.meetup.com/find/?location=\${LOC[city]}&source=EVENTS\`, verifiedOn: D, activitySignal: \`Upcoming on Meetup: \${next}\` },
    status: 'approved',
    mode: mode === 'online' ? 'online' : mode === 'hybrid' ? 'hybrid' : 'offline',
    createdAt: D,
  });
}

export const COMMUNITIES_WORLD: Community[] = [`);
let last = '';
for (const r of rows) {
  if (r.city !== last) { out.push(`  // ───────── ${r.city.toUpperCase()} ─────────`); last = r.city; }
  out.push(`  w(${q(r.city)}, ${q(r.path)}, ${q(r.name)}, ${q(r.category)}, ${q(r.what)}, ${q(`${r.event}, ${r.date}`)}, ${q(r.mode)}),`);
}
out.push('];', '');
writeFileSync('data/communities-world.ts', out.join('\n'));

// slug uniqueness check (same rule as w())
const slugs = rows.map((r) => `w-${slugify(r.city)}-${slugify(r.path)}`.slice(0, 80).replace(/-$/, ''));
const dup = slugs.filter((s, i) => slugs.indexOf(s) !== i);
if (dup.length) { console.error('duplicate slugs', dup); process.exit(1); }
console.log(`wrote ${rows.length} rows across ${new Set(rows.map((r) => r.city)).size} cities`);
